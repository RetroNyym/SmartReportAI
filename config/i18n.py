LANGUAGE = settings.language
if LANGUAGE not in LANGUAGES:
    raise ValueError(f"Unsupported LANGUAGE: {LANGUAGE}. Supported: {', '.join(LANGUAGES)}")


def t(key: str, **kwargs) -> str:
    return STRINGS[LANGUAGE][key].format(**kwargs)


def fmt_number(value: float, decimals: int = 0) -> str:
    text = f"{value:,.{decimals}f}"
    locale = LANGUAGES[LANGUAGE]
    return text.replace(",", "\0").replace(".", locale["decimal"]).replace("\0", locale["thousands"])


def fmt_datetime(value: datetime, with_time: bool = False) -> str:
    text = value.strftime(LANGUAGES[LANGUAGE]["date"])
    return f"{text} {value:%H:%M}" if with_time else text
